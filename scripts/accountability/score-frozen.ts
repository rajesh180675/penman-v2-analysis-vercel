#!/usr/bin/env tsx
/**
 * score-frozen.ts — score the frozen forecasts against results filed since.
 *
 *   npx tsx scripts/accountability/score-frozen.ts
 *
 * Every snapshot in accountability/snapshots/<made-at>/ is scored against the
 * as-filed ledger (data/filings/<SYMBOL>/as-filed.json, first filings) for the
 * years it forecast that its data never reached (scoreSnapshotAgainstFilings),
 * and the year in progress provisionally, on the months filed so far
 * (data/filings/<SYMBOL>/year-to-date.json).
 * Writes accountability/frozen-scores.json and
 * docs/generated/frozen-forecast-scores.md.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  businessChangeNote,
  firstFiledYears,
  firstFiledYearsToDate,
  scoreFrozenForecasts,
  scoresBySet,
  summarizeBands,
  summarizeScores,
  type FiledScore,
  type FiledYear,
  type FiledYearToDate,
  type ForecastSnapshot,
} from "../../src/engine/accountability";
import type { AsFiledHeadlineRecord } from "../../src/engine/filings";
import type { AsFiledYearToDateRecord } from "../filings/fetch-nse-year-to-date";

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "../..");
const SNAPSHOTS = join(ROOT, "accountability", "snapshots");

type Snapshot = ForecastSnapshot & { latestReportedPeriod?: string };

const annualRecords = (ticker: string) =>
  (JSON.parse(readFileSync(join(ROOT, "data", "filings", ticker, "as-filed.json"), "utf8")) as { records: AsFiledHeadlineRecord[] }).records;

/** Each fiscal year as first filed. */
function filedYears(ticker: string): FiledYear[] | null {
  return existsSync(join(ROOT, "data", "filings", ticker, "as-filed.json")) ? firstFiledYears(annualRecords(ticker)) : null;
}

/** Each year to date as first filed. */
function filedYearsToDate(ticker: string): FiledYearToDate[] {
  const path = join(ROOT, "data", "filings", ticker, "year-to-date.json");
  if (!existsSync(path)) return [];
  return firstFiledYearsToDate((JSON.parse(readFileSync(path, "utf8")) as { records: AsFiledYearToDateRecord[] }).records, annualRecords(ticker));
}

const sets = readdirSync(SNAPSHOTS).sort();
const load = (madeAt: string) => readdirSync(join(SNAPSHOTS, madeAt)).filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(readFileSync(join(SNAPSHOTS, madeAt, f), "utf8")) as Snapshot);

const results = scoreFrozenForecasts(sets.flatMap(load), (ticker) => {
  const years = filedYears(ticker);
  return years ? { years, yearsToDate: filedYearsToDate(ticker) } : null;
});
writeFileSync(join(ROOT, "accountability", "frozen-scores.json"), JSON.stringify(results, null, 1) + "\n");

const pct = (x: number, d = 1) => (Number.isFinite(x) ? `${(x * 100).toFixed(d)}` : "—");
const signed = (x: number, d = 1) => (Number.isFinite(x) ? `${x >= 0 ? "+" : ""}${(x * 100).toFixed(d)}` : "—");
const LABEL = { "sales-log-error": "Sales (log error, %)", "core-margin-point-error": "Core margin (points of sales)", "cni-roe-point-error": "Earnings (ROE points)" } as const;

function summary(scores: FiledScore[], metrics?: readonly FiledScore["metric"][]) {
  return summarizeScores(scores, metrics).map((s) =>
    `| ${LABEL[s.metric]} | ${s.n} | ${pct(s.model)} | ${pct(s.randomWalk)} | ${Number.isFinite(s.skill) ? `${signed(s.skill, 0)}%` : "—"} | ${signed(s.bias)} | ${s.closer} of ${s.n} |`).join("\n");
}

const MEASURE = { "sales-log-error": "Sales", "core-margin-point-error": "Core margin", "cni-roe-point-error": "Earnings" } as const;

/** Where the filed figures fell against the frozen stress and bull cases, for forecasts that record them. */
function bands(scores: FiledScore[], metrics?: readonly FiledScore["metric"][]) {
  const shares = summarizeBands(scores, metrics);
  if (!shares) return "";
  const share = (x: number) => (Number.isFinite(x) ? `${Math.round(x * 100)}%` : "—");
  const rows = shares.map((b) => `| ${MEASURE[b.metric]} | ${b.n} | ${share(b.below)} | ${share(b.within)} | ${share(b.above)} | ${share(b.belowPanic)} |`);
  return `\n\nAgainst the frozen scenario cases:\n\n| Measure | n | Below stress | Between | Above bull | Below panic |\n|---|---|---|---|---|---|\n${rows.join("\n")}`;
}

const header ="| Metric | n | Model median error | Random-walk median error | Median skill | Mean bias | Beat the random walk |\n|---|---|---|---|---|---|---|";
const latest = sets.at(-1)!;
const latestRows = results.filter((r) => r.madeAt === latest);
const report = `# Frozen forecasts, scored against results filed since

Generated by \`scripts/accountability/score-frozen.ts\`. Do not edit by hand.

Each forecast frozen in \`accountability/snapshots/\` is scored against the results the company later filed on NSE, as first filed (\`data/filings\`), for the years its data never reached. This is the out-of-sample test the walk-forward backtest can only approximate. Capitaline serves restated history, but here the actuals are what was first reported, and the forecast never saw them. Model, benchmark and actuals all come from the same filings:
- **Sales** are compared net of the excise duty a filing itemizes.
- **Core margin** is operating income after tax over sales, built from the filed lines on the recast's tax rules, the associates' share inside profit before tax as Capitaline files it (\`src/engine/accountability/filedCoreIncome.ts\`). It is scored as a move from the cutoff year: the forecast's margin less the one it started from, against the filed margin less the cutoff year's. The recast and the filings measure the level a median 0.5 points apart, which a move cancels; their moves differ by a median 0.20 points (into FY2023–FY2026, 7% of them by more than a point). Only forecasts that record the year they started from are scored on it: snapshots of schema v3, frozen from 2026-10-19 on.
- **Earnings** compare forecast CNI with the owners' profit filed (OCI aside), in points of the opening year's filed owners' equity.
- **Random walk** is "the cutoff year again". **Skill** = 1 − median error / random-walk median error.
- **Scenario bands.** Snapshots of schema v4 also record the stress, bull and historical-panic cases, and each filed figure is placed below stress, between stress and bull, or above bull, on the basis its base case is scored on (the margin moved from the cutoff year's filed margin). The bands were calibrated on the walk-forward (\`docs/generated/scenario-band-coverage.md\`), so this tests them on years the calibration never saw. Sets frozen before v4 have no band table.
- **The year in progress** is scored provisionally, apart from the filed years, on the months filed so far (\`data/filings/<SYMBOL>/year-to-date.json\`, \`scripts/filings/fetch-nse-year-to-date.ts\`). They are set against the same months a year before, so seasonality cancels: the last full year's sales grown as those months grew, and its core margin moved as theirs moved. Earnings are not projected, since one quarter's one-offs weigh too much in part of a year. A provisional score is replaced when the year is filed.
- **One-offs.** Filed profit includes them on both sides. ITC's FY2025 owners' profit carries the hotels demerger gain, so its random walk for FY2026, from a cutoff in FY2025, misses by 20 ROE points. The forecast models neither.

Not scored:
- years the forecast's data already covered: an anchor that walked back was built on later years too;
- forecasts of a business the consolidated filings do not describe (a lending arm carved out, standalone accounts);
- years from a filing that reports discontinued operations of at least 0.5% of revenue: a business sold or demerged after the forecast was made, whose later filings describe a smaller business than the forecast's (Hindustan Unilever's ice cream, FY2026; ITC's hotels, FY2025).

## By frozen set

${scoresBySet(results).map(({ madeAt, forecasts, scored, final, provisional, provisionalMonths }) => {
    const inProgress = provisional.length
      ? `\n\nThe year in progress, projected from the months filed so far (provisional; ${provisionalMonths == null ? "months filed differ by company" : `${provisionalMonths} months`}):\n\n${header}\n${summary(provisional, ["sales-log-error", "core-margin-point-error"])}${bands(provisional, ["sales-log-error", "core-margin-point-error"])}`
      : "";
    return `### Frozen ${madeAt} (${scored} of ${forecasts} forecasts scored)\n\n${header}\n${summary(final)}${bands(final)}${inProgress}`;
  }).join("\n\n")}

## Frozen ${latest}, by company

| Company | Cutoff | Year | Sales error | Random walk | Margin error (pts) | Random walk | Earnings error (ROE pts) | Random walk |
|---|---|---|---|---|---|---|---|---|
${latestRows.flatMap((r) => {
    if (r.skipped) return [`| ${r.ticker} | ${r.cutoff} | — | not scored: ${r.skipped} | | | | | |`];
    if (!r.scores.length) return [`| ${r.ticker} | ${r.cutoff} | — | no filed year after its data yet | | | | | |`];
    const years = [...new Set(r.scores.map((s) => s.periodEnd))];
    return years.map((y) => {
      const cell = (metric: FiledScore["metric"]) => {
        const x = r.scores.find((s) => s.periodEnd === y && s.metric === metric);
        return x ? `${signed(x.model)} | ${signed(x.randomWalk)}` : "— | —";
      };
      const months = r.scores.find((s) => s.periodEnd === y)?.provisional?.months;
      return `| ${r.ticker} | ${r.cutoff} | ${y}${months ? ` (${months} months filed)` : ""} | ${cell("sales-log-error")} | ${cell("core-margin-point-error")} | ${cell("cni-roe-point-error")} |`;
    }).concat(r.businessChange ? [`| ${r.ticker} | ${r.cutoff} | ${r.businessChange.fiscalYearEnd} on | not scored: ${businessChangeNote(r.businessChange)} | | | | | |`] : []);
  }).join("\n")}
`;
writeFileSync(join(ROOT, "docs", "generated", "frozen-forecast-scores.md"), report);
console.log(`${results.filter((r) => r.scores.length).length} of ${results.length} frozen forecasts scored across ${sets.length} sets.`);
