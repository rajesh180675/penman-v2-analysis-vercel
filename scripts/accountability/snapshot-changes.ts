#!/usr/bin/env tsx
/**
 * snapshot-changes.ts — what moved in each company's frozen base case from one
 * snapshot set to the next.
 *
 *   npx tsx scripts/accountability/snapshot-changes.ts
 *
 * Reads accountability/snapshots/<made-at>/ (never modified) and writes
 * docs/generated/frozen-forecast-changes.md: for each pair of consecutive sets,
 * the value, the capital costs and the year-one drivers of every company frozen
 * in both. It records change; it does not attribute it.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compareSnapshots, type ForecastSnapshot, type SnapshotChange } from "../../src/engine/accountability";

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "../..");
const SNAPSHOTS = join(ROOT, "accountability", "snapshots");
/** A value that moved less than this is counted, not listed. */
const LISTED_CHANGE = 0.005;

const sets = existsSync(SNAPSHOTS) ? readdirSync(SNAPSHOTS).sort() : [];
const load = (madeAt: string) => readdirSync(join(SNAPSHOTS, madeAt)).filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(readFileSync(join(SNAPSHOTS, madeAt, f), "utf8")) as ForecastSnapshot);

const pct = (x: number | null, digits = 1) => (x == null ? "—" : `${x < 0 ? "−" : ""}${Math.abs(x * 100).toFixed(digits)}%`);
const signedPct = (x: number | null) => (x == null ? "—" : `${x >= 0 ? "+" : "−"}${Math.abs(x * 100).toFixed(1)}%`);
const points = (x: number) => (Math.abs(x) < 0.00005 ? "—" : `${x >= 0 ? "+" : "−"}${Math.abs(x * 100).toFixed(2)}`);
const rupees = (x: number | null) => (x == null ? "—" : `${x < 0 ? "−" : ""}₹${Math.abs(x).toLocaleString("en-IN", { maximumFractionDigits: Math.abs(x) >= 100 ? 0 : 1 })}`);
const pair = (a: number | null, b: number | null, f: (x: number | null) => string) => (f(a) === f(b) ? f(b) : `${f(a)} → ${f(b)}`);
const times = (x: number | null) => (x == null ? "—" : `${x.toFixed(2)}×`);

function section(fromSet: string, toSet: string, earlier: ForecastSnapshot[], later: ForecastSnapshot[]): string[] {
  const changes = compareSnapshots(earlier, later);
  const listed = changes
    .filter((c) => c.basisChange != null || c.valueChange == null || Math.abs(c.valueChange) >= LISTED_CHANGE)
    .sort((x, y) => Math.abs(y.valueChange ?? 0) - Math.abs(x.valueChange ?? 0));
  const unlisted = changes.length - listed.length;
  const added = later.filter((s) => !earlier.some((e) => e.ticker === s.ticker)).map((s) => s.ticker);
  const dropped = earlier.filter((s) => !later.some((e) => e.ticker === s.ticker)).map((s) => s.ticker);
  const lines = [
    `## ${fromSet} → ${toSet}`,
    "",
    `${changes.length} companies frozen in both sets. ${listed.length} listed below; ${unlisted} moved by less than ${pct(LISTED_CHANGE)} with the same anchor and basis.`,
  ];
  if (added.length) lines.push(`Frozen only in ${toSet}: ${added.join(", ")}.`);
  if (dropped.length) lines.push(`Frozen only in ${fromSet}: ${dropped.join(", ")}.`);
  // Snapshots before schema v2 record no basis, so a carved lending arm or a
  // change of accounts cannot be seen against them.
  const unrecorded = [[fromSet, earlier], [toSet, later]].filter(([, set]) => (set as ForecastSnapshot[]).some((s) => !s.basis)).map(([name]) => name);
  if (unrecorded.length) lines.push(`The ${unrecorded.join(" and ")} ${unrecorded.length > 1 ? "sets record" : "set records"} no basis (snapshot schema v1), so a carved lending arm or a change of accounts does not show in this comparison.`);
  lines.push("");
  if (listed.length) {
    lines.push("| Company | Value per share | Change | ke (pp) | kw (pp) | g (pp) | Year-one margin | Year-one turnover | Anchor or basis |");
    lines.push("|---|---|---|---|---|---|---|---|---|");
    const recorded = (t: string) => [earlier, later].every((set) => set.find((s) => s.ticker === t)?.basis != null);
    for (const c of listed as SnapshotChange[]) {
      lines.push(`| ${c.ticker} | ${pair(c.value.from, c.value.to, rupees)} | ${signedPct(c.valueChange)} | ${points(c.ke)} | ${points(c.kw)} | ${points(c.g)} | ${pair(c.margin.from, c.margin.to, (x) => pct(x))} | ${pair(c.turnover.from, c.turnover.to, times)} | ${c.basisChange ?? (recorded(c.ticker) ? "same" : "same anchor")} |`);
    }
    lines.push("");
  }
  return lines;
}

const body = [
  "# Frozen forecasts, set to set",
  "",
  "Generated by `scripts/accountability/snapshot-changes.ts`. Do not edit by hand.",
  "",
  "Each set in `accountability/snapshots/` freezes the base case the app made that day. Between two sets the same company's value moves with the engine merged in between, the pinned market inputs and, where its anchor moved, the data. This lists what moved beside the value: the capital costs, and the year-one margin (operating income over sales) and turnover (sales over year-end NOA) the forecast starts from. It does not attribute the value change to any one of them.",
  "",
  ...(sets.length < 2 ? ["Fewer than two frozen sets: nothing to compare yet.", ""] : sets.slice(1).flatMap((toSet, i) => section(sets[i]!, toSet, load(sets[i]!), load(toSet)))),
];
writeFileSync(join(ROOT, "docs", "generated", "frozen-forecast-changes.md"), body.join("\n"));
console.log(`Compared ${Math.max(sets.length - 1, 0)} pairs of frozen sets → docs/generated/frozen-forecast-changes.md`);
