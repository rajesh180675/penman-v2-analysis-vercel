#!/usr/bin/env tsx
/**
 * snapshot-changes.ts — what moved in each company's frozen base case from one
 * snapshot set to the next.
 *
 *   npx tsx scripts/accountability/snapshot-changes.ts
 *
 * Reads accountability/snapshots/<made-at>/ (never modified) and writes
 * docs/generated/frozen-forecast-changes.md: for each pair of consecutive sets,
 * the value, the capital costs and the year-one drivers of every company frozen
 * in both. It records change; it does not attribute it. The Record page shows
 * the same comparison (compareSnapshotSets), cell for cell.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  compareSnapshotSets,
  LISTED_VALUE_CHANGE,
  SNAPSHOT_CHANGE_COLUMNS,
  snapshotChangeCells,
  type ForecastSnapshot,
  type SnapshotSetChanges,
} from "../../src/engine/accountability";

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "../..");
const SNAPSHOTS = join(ROOT, "accountability", "snapshots");

const sets = existsSync(SNAPSHOTS) ? readdirSync(SNAPSHOTS).sort() : [];
const load = (madeAt: string) => readdirSync(join(SNAPSHOTS, madeAt)).filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(readFileSync(join(SNAPSHOTS, madeAt, f), "utf8")) as ForecastSnapshot);

function section(pair: SnapshotSetChanges): string[] {
  const lines = [
    `## ${pair.from} → ${pair.to}`,
    "",
    `${pair.compared} companies frozen in both sets. ${pair.listed.length} listed below; ${pair.compared - pair.listed.length} moved by less than ${(LISTED_VALUE_CHANGE * 100).toFixed(1)}% with the same anchor and basis.`,
  ];
  if (pair.added.length) lines.push(`Frozen only in ${pair.to}: ${pair.added.join(", ")}.`);
  if (pair.dropped.length) lines.push(`Frozen only in ${pair.from}: ${pair.dropped.join(", ")}.`);
  // Snapshots before schema v2 record no basis, so a carved lending arm or a
  // change of accounts cannot be seen against them.
  const unrecorded = pair.unrecordedBasis;
  if (unrecorded.length) lines.push(`The ${unrecorded.join(" and ")} ${unrecorded.length > 1 ? "sets record" : "set records"} no basis (snapshot schema v1), so a carved lending arm or a change of accounts does not show in this comparison.`);
  lines.push("");
  if (pair.listed.length) {
    lines.push(`| ${SNAPSHOT_CHANGE_COLUMNS.join(" | ")} |`);
    lines.push(`|${SNAPSHOT_CHANGE_COLUMNS.map(() => "---").join("|")}|`);
    for (const c of pair.listed) lines.push(`| ${snapshotChangeCells(c).join(" | ")} |`);
    lines.push("");
  }
  return lines;
}

const body = [
  "# Frozen forecasts, set to set",
  "",
  "Generated by `scripts/accountability/snapshot-changes.ts`. Do not edit by hand.",
  "",
  "Each set in `accountability/snapshots/` freezes the base case the app made that day. Between two sets the same company's value moves with the engine merged in between, the pinned market inputs and, where its anchor moved, the data. This lists what moved beside the value: the capital costs, and the year-one margin (operating income over sales) and turnover (sales over year-end NOA) the forecast starts from. It does not attribute the value change to any one of them.",
  "",
  ...(sets.length < 2 ? ["Fewer than two frozen sets: nothing to compare yet.", ""] : compareSnapshotSets(sets.flatMap(load)).flatMap(section)),
];
writeFileSync(join(ROOT, "docs", "generated", "frozen-forecast-changes.md"), body.join("\n"));
console.log(`Compared ${Math.max(sets.length - 1, 0)} pairs of frozen sets → docs/generated/frozen-forecast-changes.md`);
