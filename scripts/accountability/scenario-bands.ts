#!/usr/bin/env tsx
/**
 * scenario-bands.ts — where filed outcomes fell against the stress and bull
 * forecasts the app would have made, over the industrial registry.
 *
 *   npm run accountability:bands -- [--made-at=YYYY-MM-DD] [--skip-runs]
 *   npm run accountability:bands -- --ticker=ITC        (one company, one process)
 *
 * Each company runs in its own process (the corpus in one process exhausts
 * memory on Windows) on the walk-forward's valuation basis
 * (scripts/lib/walkForwardBasis.ts), writing accountability/bands/<ticker>.json.
 * The aggregate goes to docs/generated/scenario-band-coverage.md. Unlike
 * run-all.ts, it freezes no snapshot and regenerates no prior.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import type { LibraryCompany } from "../../src/components/data-entry/companyRegistry";
import { summarizeScenarioBands, walkForwardScenarioBands, type ScenarioBandObservation, type ScenarioBandSummary } from "../../src/engine/accountability";
import { loadWalkForwardBasis } from "../lib/walkForwardBasis";

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "../..");
const RAW_LOADER = join(ROOT, "scripts", "lib", "register-raw-loader.mjs");
const OUT_DIR = join(ROOT, "accountability", "bands");
const arg = (name: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split("=")[1] ?? null;
const madeAt = arg("made-at") ?? new Date().toISOString().slice(0, 10);
const ticker = arg("ticker");
const registry: LibraryCompany[] = JSON.parse(readFileSync(join(ROOT, "public", "data", "companies", "registry.json"), "utf-8"));
const FINANCIAL = new Set(["bank", "nbfc", "insurance"]);

interface BandsFile {
  readonly ticker: string;
  readonly skipped?: string;
  readonly observations?: ScenarioBandObservation[];
}

if (ticker) {
  const company = registry.find((c) => c.ticker === ticker);
  if (!company) throw new Error(`Unknown ticker ${ticker}`);
  mkdirSync(OUT_DIR, { recursive: true });
  const loaded = await loadWalkForwardBasis(ROOT, company, madeAt);
  const file: BandsFile = loaded.status === "skipped"
    ? { ticker, skipped: loaded.reason }
    : { ticker, observations: walkForwardScenarioBands(loaded.periods, loaded.config) };
  writeFileSync(join(OUT_DIR, `${ticker}.json`), JSON.stringify(file) + "\n");
  process.exit(0);
}

const industrial = registry.filter((c) => !FINANCIAL.has(c.type));
if (!process.argv.includes("--skip-runs")) {
  for (const company of industrial) {
    const started = Date.now();
    const result = spawnSync(process.execPath, ["--import", "tsx/esm", "--import", pathToFileURL(RAW_LOADER).href, "scripts/accountability/scenario-bands.ts", `--ticker=${company.ticker}`, `--made-at=${madeAt}`], {
      cwd: ROOT,
      encoding: "utf8",
      timeout: 300_000,
    });
    const status = result.status === 0 ? "ok" : `FAILED (${result.status}) ${(result.stderr ?? "").split("\n").slice(-3).join(" ")}`;
    console.log(`${company.ticker.padEnd(12)} ${status} ${((Date.now() - started) / 1000).toFixed(0)}s`);
  }
}

const files: BandsFile[] = industrial.flatMap((c) => {
  const path = join(OUT_DIR, `${c.ticker}.json`);
  return existsSync(path) ? [JSON.parse(readFileSync(path, "utf-8")) as BandsFile] : [];
});
const scored = files.filter((f) => f.observations?.length);
const all = scored.flatMap((f) => f.observations!);
const cutoffs = scored.reduce((n, f) => n + new Set(f.observations!.map((o) => o.cutoffPeriod)).size, 0);

const pct = (v: number | null | undefined) => (v == null ? "—" : `${(v * 100).toFixed(0)}%`);
const ratio = (v: number | null | undefined) => (v == null ? "—" : v.toFixed(2));
const table = (rows: readonly ScenarioBandSummary[]) => [
  "| Metric | Year ahead | n | Below stress | Between | Above bull | Below panic | Stress / base | Bull / base | Filed / base: p10 · p20 · p50 · p80 · p90 |",
  "|---|---|---|---|---|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.metric === "sales" ? "Sales" : "CNI"} | ${r.horizon} | ${r.n} | ${pct(r.below)} | ${pct(r.within)} | ${pct(r.above)} | ${pct(r.belowPanic)} | ${ratio(r.stressToBase)} | ${ratio(r.bullToBase)} | ${r.actualToBase ? [r.actualToBase.p10, r.actualToBase.p20, r.actualToBase.p50, r.actualToBase.p80, r.actualToBase.p90].map(ratio).join(" · ") : "—"} |`),
];
const oneYear = (f: BandsFile, metric: "sales" | "cni") => summarizeScenarioBands(f.observations!.filter((o) => o.metric === metric && o.horizon === 1))[0];

const report = [
  "# Scenario band coverage",
  "",
  `Generated by \`scripts/accountability/scenario-bands.ts\` on ${madeAt}. Do not edit by hand.`,
  "",
  "At every walk-forward cutoff (at least 5 years of history, the same cutoffs, capital costs and valuation basis as [forecast accountability](forecast-accountability.md)) the app's historical-panic, stress, base and bull forecasts are rebuilt from the history up to the cutoff, and each of the next three years' filed sales and CNI is placed against them:",
  "",
  "- **below stress**, **between** stress and bull, or **above bull**;",
  "- **below panic**: below the historical-panic path as well.",
  "",
  "A stress or bull case that means what its name says leaves a minority of filed outcomes beyond it. The columns on the right set each path and the filed outcome against the base forecast, over observations with a positive base: the medians of stress / base and bull / base, and the quantiles of filed / base. The base forecast's own accuracy is in the accountability report.",
  "",
  "> **Caveat — restated data.** As in the accountability report, Capitaline serves the latest restated figures, so a cutoff can see restatements of its own history.",
  "",
  `## All industrial companies (${scored.length} companies, ${cutoffs} cutoffs)`,
  "",
  ...table(summarizeScenarioBands(all)),
  "",
  "## By company, one year ahead",
  "",
  "| Company | Cutoffs | Sales below stress | Sales above bull | CNI below stress | CNI above bull |",
  "|---|---|---|---|---|---|",
  ...scored.map((f) => {
    const sales = oneYear(f, "sales");
    const cni = oneYear(f, "cni");
    return `| ${f.ticker} | ${sales?.n ?? 0} | ${pct(sales?.below)} | ${pct(sales?.above)} | ${pct(cni?.below)} | ${pct(cni?.above)} |`;
  }),
  "",
  ...(files.some((f) => f.skipped) ? ["## Not scored", "", ...files.filter((f) => f.skipped).map((f) => `- ${f.ticker}: ${f.skipped}`), ""] : []),
].join("\n");

writeFileSync(join(ROOT, "docs", "generated", "scenario-band-coverage.md"), report);
console.log(`\n${scored.length} companies, ${all.length} observations → docs/generated/scenario-band-coverage.md`);
